"""
{node_name}.py
Production-grade differential drive controller generated by RoboSage.
Features:
- Automatic zero-velocity E-Stop on shutdown/crash.
- LaserScan timeout watchdog to prevent operating on frozen sensor data.
- Strict NaN / Inf filtering on sensor ranges.
- Best-effort sensor data QoS profile matching standard LiDAR drivers.
"""

import math
import sys
import rclpy
from rclpy.node import Node
from rclpy.qos import qos_profile_sensor_data
from geometry_msgs.msg import Twist
from sensor_msgs.msg import LaserScan


class SafeDiffDriveController(Node):

    def __init__(self):
        super().__init__('{node_name}')

        # Parameters
        self.declare_parameter('linear_speed', 0.25)
        self.declare_parameter('min_obstacle_dist', 0.5)
        self.declare_parameter('watchdog_timeout_sec', 0.6)

        self.linear_speed = self.get_parameter('linear_speed').value
        self.min_obstacle_dist = self.get_parameter('min_obstacle_dist').value
        self.watchdog_timeout = self.get_parameter('watchdog_timeout_sec').value

        # Publishers & Subscribers
        self.cmd_vel_pub = self.create_publisher(Twist, 'cmd_vel', 10)
        
        # Best-effort QoS matches standard LiDAR drivers (e.g. RPLiDAR, Hokuyo)
        self.scan_sub = self.create_subscription(
            LaserScan,
            'scan',
            self.scan_callback,
            qos_profile_sensor_data
        )

        # State & Watchdog
        self.last_scan_time = self.get_clock().now()
        self.watchdog_timer = self.create_timer(0.2, self.watchdog_check)
        self.is_stopped = False

        self.get_logger().info('{node_name} initialized with safety watchdogs.')

    def scan_callback(self, msg: LaserScan):
        # Update watchdog timestamp
        self.last_scan_time = self.get_clock().now()

        # Sanitize ranges: filter out NaN, Inf, and out-of-spec readings
        valid_ranges = [
            r for r in msg.ranges 
            if math.isfinite(r) and msg.range_min <= r <= msg.range_max
        ]

        if not valid_ranges:
            self.get_logger().warn('No valid laser scan readings received; halting robot.')
            self.stop_robot()
            return

        min_distance = min(valid_ranges)

        cmd = Twist()
        if min_distance < self.min_obstacle_dist:
            self.get_logger().info(f'Obstacle detected at {{min_distance:.2f}}m! Turning.')
            cmd.linear.x = 0.0
            cmd.angular.z = 0.5  # Rotate away
        else:
            cmd.linear.x = self.linear_speed
            cmd.angular.z = 0.0

        self.cmd_vel_pub.publish(cmd)
        self.is_stopped = False

    def watchdog_check(self):
        """Halts motors if sensor stream freezes or stops publishing."""
        elapsed = (self.get_clock().now() - self.last_scan_time).nanoseconds / 1e9
        if elapsed > self.watchdog_timeout and not self.is_stopped:
            self.get_logger().error(
                f'WATCHDOG TRIGGERED: No scan received in {{elapsed:.2f}}s! Commanding emergency stop.'
            )
            self.stop_robot()

    def stop_robot(self):
        """Publishes zero velocity."""
        stop_cmd = Twist()
        self.cmd_vel_pub.publish(stop_cmd)
        self.is_stopped = True


def main(args=None):
    rclpy.init(args=args)
    node = SafeDiffDriveController()

    try:
        rclpy.spin(node)
    except KeyboardInterrupt:
        pass
    finally:
        # Crucial: publish zero velocity before node destruction!
        node.get_logger().info('Shutting down: publishing safe zero velocity.')
        node.stop_robot()
        node.destroy_node()
        rclpy.shutdown()


if __name__ == '__main__':
    main()
