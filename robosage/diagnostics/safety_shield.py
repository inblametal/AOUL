"""
Safety Shield Deterministic Runtime Middleware.
Implements kinematic velocity, acceleration, and obstacle-distance envelope clamping
to prevent runaway robots, motor overload, and high-speed impacts.
"""

import math
from typing import Any, Dict


class SafetyShieldEngine:
    """Computes dynamic safety bounds and generates verified Safety Shield middleware."""

    @staticmethod
    def calculate_envelope(
        commanded_linear_vel: float,
        commanded_angular_vel: float,
        current_distance_to_obstacle: float,
        max_linear_vel: float = 1.0,
        max_angular_vel: float = 1.5,
        max_linear_accel: float = 0.8,
        min_safe_distance: float = 0.35,
        latency_seconds: float = 0.05,
    ) -> Dict[str, Any]:
        """
        Calculates safe velocity using dynamic braking curve:
        v_max_safe(d) = sqrt(2 * a_max * max(0, d - d_safe - v * latency))
        """
        # Step 1: Clamp within static mechanical limits
        vel_cmd = max(-max_linear_vel, min(max_linear_vel, commanded_linear_vel))
        ang_cmd = max(-max_angular_vel, min(max_angular_vel, commanded_angular_vel))

        # Step 2: Distance available after communication and compute latency
        effective_dist = max(0.0, current_distance_to_obstacle - (vel_cmd * latency_seconds) - min_safe_distance)

        # Step 3: Maximum safe velocity without exceeding max deceleration
        if effective_dist <= 0.0:
            safe_linear_vel = 0.0
            intervention_reason = "CRITICAL: Obstacle inside emergency stop buffer. Clamped to 0.0 m/s."
            is_clamped = True
        else:
            max_permitted_vel = math.sqrt(2.0 * max_linear_accel * effective_dist)
            if vel_cmd > max_permitted_vel:
                safe_linear_vel = max_permitted_vel
                intervention_reason = (
                    f"WARNING: Commanded {vel_cmd:.2f} m/s exceeds dynamic braking limit "
                    f"({max_permitted_vel:.2f} m/s for {current_distance_to_obstacle:.2f}m obstacle distance)."
                )
                is_clamped = True
            else:
                safe_linear_vel = vel_cmd
                intervention_reason = "NOMINAL: Commanded velocity satisfies dynamic braking envelope."
                is_clamped = False

        # Calculate stopping distance at current velocity
        stopping_distance = (vel_cmd ** 2) / (2.0 * max_linear_accel) if max_linear_accel > 0 else 0.0

        return {
            "commanded_linear_vel": round(commanded_linear_vel, 3),
            "commanded_angular_vel": round(commanded_angular_vel, 3),
            "safe_linear_vel": round(safe_linear_vel, 3),
            "safe_angular_vel": round(ang_cmd, 3),
            "stopping_distance_required": round(stopping_distance, 3),
            "obstacle_distance": round(current_distance_to_obstacle, 3),
            "is_clamped": is_clamped,
            "intervention_reason": intervention_reason,
            "safety_margin_m": round(max(0.0, current_distance_to_obstacle - stopping_distance - min_safe_distance), 3),
        }

    @staticmethod
    def generate_cpp_shield_node(node_name: str = "safety_shield_node") -> str:
        return f"""// Generated by AOUL Robotics Copilot
// Safety Shield Middleware: Dynamic Velocity & Collision Clamping Node
#include <memory>
#include <algorithm>
#include <cmath>
#include "rclcpp/rclcpp.hpp"
#include "geometry_msgs/msg/twist.hpp"
#include "sensor_msgs/msg/laser_scan.hpp"

class {node_name} : public rclcpp::Node {{
public:
  {node_name}() : Node("{node_name}"), min_obstacle_dist_(10.0) {{
    // Parameters
    this->declare_parameter("max_linear_vel", 1.0);
    this->declare_parameter("max_linear_accel", 0.8);
    this->declare_parameter("min_safe_dist", 0.35);

    // Subscriptions
    raw_cmd_sub_ = this->create_subscription<geometry_msgs::msg::Twist>(
      "cmd_vel_raw", 10, std::bind(&{node_name}::cmdCallback, this, std::placeholders::_1));

    scan_sub_ = this->create_subscription<sensor_msgs::msg::LaserScan>(
      "scan", rclcpp::SensorDataQoS(), std::bind(&{node_name}::scanCallback, this, std::placeholders::_1));

    // Shielded Publisher
    safe_cmd_pub_ = this->create_publisher<geometry_msgs::msg::Twist>("cmd_vel", 10);

    RCLCPP_INFO(this->get_logger(), "🛡️ AOUL Safety Shield Interceptor active.");
  }}

  ~{node_name}() {{
    // Guaranteed E-Stop Zero-Velocity on Shutdown
    geometry_msgs::msg::Twist stop_msg;
    stop_msg.linear.x = 0.0;
    stop_msg.angular.z = 0.0;
    safe_cmd_pub_->publish(stop_msg);
  }}

private:
  void scanCallback(const sensor_msgs::msg::LaserScan::SharedPtr msg) {{
    float min_d = 100.0f;
    for (float r : msg->ranges) {{
      if (std::isfinite(r) && r > msg->range_min && r < msg->range_max) {{
        min_d = std::min(min_d, r);
      }}
    }}
    min_obstacle_dist_ = min_d;
  }}

  void cmdCallback(const geometry_msgs::msg::Twist::SharedPtr raw_msg) {{
    double a_max = this->get_parameter("max_linear_accel").as_double();
    double d_safe = this->get_parameter("min_safe_dist").as_double();
    double v_cmd = raw_msg->linear.x;

    geometry_msgs::msg::Twist safe_msg = *raw_msg;
    double d_eff = std::max(0.0, min_obstacle_dist_ - d_safe);

    if (d_eff <= 0.0) {{
      safe_msg.linear.x = 0.0; // Hard clamp
    }} else {{
      double v_max_safe = std::sqrt(2.0 * a_max * d_eff);
      safe_msg.linear.x = std::min(v_cmd, v_max_safe);
    }}

    safe_cmd_pub_->publish(safe_msg);
  }}

  rclcpp::Subscription<geometry_msgs::msg::Twist>::SharedPtr raw_cmd_sub_;
  rclcpp::Subscription<sensor_msgs::msg::LaserScan>::SharedPtr scan_sub_;
  rclcpp::Publisher<geometry_msgs::msg::Twist>::SharedPtr safe_cmd_pub_;
  double min_obstacle_dist_;
}};

int main(int argc, char **argv) {{
  rclcpp::init(argc, argv);
  rclcpp::spin(std::make_shared<{node_name}>());
  rclcpp::shutdown();
  return 0;
}}
"""

    @staticmethod
    def generate_python_shield_node(node_name: str = "safety_shield_node") -> str:
        return f"""#!/usr/bin/env python3
# Generated by AOUL Robotics Copilot
# Safety Shield Middleware: Dynamic Velocity & Collision Clamping Node
import math
import rclpy
from rclpy.node import Node
from rclpy.qos import qos_profile_sensor_data
from geometry_msgs.msg import Twist
from sensor_msgs.msg import LaserScan

class {node_name}(Node):
    def __init__(self):
        super().__init__('{node_name}')
        self.declare_parameter('max_linear_vel', 1.0)
        self.declare_parameter('max_linear_accel', 0.8)
        self.declare_parameter('min_safe_dist', 0.35)

        self.min_obstacle_dist = 10.0

        # Subscriptions
        self.raw_sub = self.create_subscription(Twist, 'cmd_vel_raw', self._cmd_cb, 10)
        self.scan_sub = self.create_subscription(LaserScan, 'scan', self._scan_cb, qos_profile_sensor_data)

        # Shielded publisher
        self.safe_pub = self.create_publisher(Twist, 'cmd_vel', 10)
        self.get_logger().info('🛡️ AOUL Safety Shield Interceptor active.')

    def _scan_cb(self, msg: LaserScan):
        valid = [r for r in msg.ranges if math.isfinite(r) and msg.range_min < r < msg.range_max]
        if valid:
            self.min_obstacle_dist = min(valid)

    def _cmd_cb(self, raw_cmd: Twist):
        a_max = self.get_parameter('max_linear_accel').value
        d_safe = self.get_parameter('min_safe_dist').value
        v_cmd = raw_cmd.linear.x

        safe_cmd = Twist()
        safe_cmd.angular = raw_cmd.angular

        d_eff = max(0.0, self.min_obstacle_dist - d_safe)
        if d_eff <= 0.0:
            safe_cmd.linear.x = 0.0  # Immediate clamp
        else:
            v_max_safe = math.sqrt(2.0 * a_max * d_eff)
            safe_cmd.linear.x = min(v_cmd, v_max_safe)

        self.safe_pub.publish(safe_cmd)

    def destroy_node(self):
        # Guaranteed Zero-Velocity E-Stop on shutdown
        stop = Twist()
        self.safe_pub.publish(stop)
        super().destroy_node()

def main(args=None):
    rclpy.init(args=args)
    node = {node_name}()
    try:
        rclpy.spin(node)
    except KeyboardInterrupt:
        pass
    finally:
        node.destroy_node()
        rclpy.shutdown()

if __name__ == '__main__':
    main()
"""
